create table categories (
    id   integer generated by default as identity primary key,
    name varchar(60) not null unique
);

create table users (
    id            integer     generated by default as identity primary key,
    username      varchar(60) not null unique,
    display_name  varchar(60) not null,
    password_hash varchar(100) not null,
    role          varchar(16) not null default 'ROLE_USER',
    enabled       boolean     not null default true,
    created_at    timestamp   not null default current_timestamp
);

create table questions (
    id          integer generated by default as identity primary key,
    text        varchar not null,
    option_1    varchar not null,
    option_2    varchar not null,
    option_3    varchar not null,
    option_4    varchar not null,
    answer      varchar not null,
    category_id integer references categories (id),
    difficulty  varchar(6) not null default 'MEDIUM',
    created_at  timestamp  not null default current_timestamp,
    constraint questions_answer_is_an_option
        check (answer in (option_1, option_2, option_3, option_4)),
    constraint questions_difficulty_is_known
        check (difficulty in ('EASY', 'MEDIUM', 'HARD'))
);

create table rounds (
    id            integer generated by default as identity primary key,
    user_id       integer references users (id),
    mode          varchar(16) not null default 'SOLO',
    started_at    timestamp   not null default current_timestamp,
    finished_at   timestamp,
    score         integer     not null default 0,
    correct_count integer     not null default 0,
    wrong_count   integer     not null default 0
);

create index rounds_by_user on rounds (user_id);
